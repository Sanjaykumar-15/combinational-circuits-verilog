module mux_16_to_1(
    input  [15:0] d,
    input  [3:0]  s,
    output y
);

    assign y = d[s];

endmodule

module tb_mux_16_to_1;

    reg  [15:0] d;
    reg  [3:0]  s;

    wire y;

    mux_16_to_1 dut(
        .d(d),
        .s(s),
        .y(y)
    );

